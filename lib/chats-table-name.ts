/**
 * Naming rules for the per-client conversation tables in the "chats" Supabase
 * project. Pure module (no Supabase imports) so the Nuevo cliente modal can
 * preview the table name in the browser while the user types.
 *
 * The house style is chats_ + the client name with accents, spaces and
 * punctuation removed, capitalization untouched: "Bad Boys Toys" ->
 * chats_BadBoysToys, matching chats_BadBoysToys / chats_SIWCopackers in the
 * live project.
 */

/**
 * A chats_* table name is interpolated into the PostgREST path and into the
 * CREATE TABLE below (it can't be a bound parameter in either), so it must be
 * validated before use. Restricting to the chats_ prefix + word chars makes
 * injection impossible and scopes access to conversation tables only.
 */
export const CHATS_TABLE_RE = /^chats_[A-Za-z0-9_]+$/;

export function isValidChatsTable(name: string): boolean {
  return CHATS_TABLE_RE.test(name);
}

/**
 * Suggests the table name for a client. Returns null when the name has no
 * alphanumerics to work with (e.g. "!!!"), so callers can disable the option
 * instead of building an invalid identifier.
 */
export function chatsTableName(clientName: string): string | null {
  const stem = clientName
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^A-Za-z0-9]/g, "");
  return stem ? `chats_${stem}` : null;
}

/**
 * The fixed DDL for a new conversation table, byte-identical in shape to the
 * tables the agents already write to (id / created_at / numero_de_mensajes /
 * id_de_kommo / historial, RLS on, no policies: service_role bypasses it).
 *
 * This is the ONLY SQL the app ever sends to the chats project, and the name is
 * validated first, so nothing user-authored reaches the database. The
 * identifier is double-quoted because the names carry capitals. NOTIFY pgrst
 * refreshes PostgREST's schema cache so the history panel sees the table
 * immediately instead of 404-ing until the next reload.
 */
export function buildCreateChatsTableSql(tableName: string): string {
  if (!isValidChatsTable(tableName)) {
    throw new Error(`Nombre de tabla inválido: ${tableName}`);
  }
  return `create table if not exists public."${tableName}" (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  numero_de_mensajes numeric,
  id_de_kommo text,
  historial text,
  -- One object per turn: rol, texto, estado, ts. The historial column keeps
  -- the flat text the agents have always written; this is the parseable
  -- version, the only one that survives a message containing User: or IA:.
  turnos jsonb
);
alter table public."${tableName}" enable row level security;
notify pgrst, 'reload schema';`;
}
